#!/usr/bin/env node
// SPDX-License-Identifier: MIT
// Generates packages/launch-sdk/src/types/project-schema.d.ts from the REAL exports of
// `@relics/project-schema`, by importing it and reflecting on what it actually exposes.
//
// WHY GENERATED RATHER THAN HAND-WRITTEN. `@relics/project-schema` is dependency-free plain ESM
// with no TypeScript of its own, and that is a deliberate property of the OFFLINE kit which must
// not change to suit a networked package. The alternative — a hand-maintained list of its members —
// is a SECOND declaration of the schema's surface, and this repo has already been bitten by every
// flavour of that: a hand-typed field order, a hand-typed copy word, a hand-built selector string.
// Reflection cannot fall behind the module it reflects.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "packages", "launch-sdk", "src", "types", "project-schema.d.ts");

const mod = await import(join(HERE, "..", "packages", "project-schema", "index.js"));

/** A structural TypeScript type for a runtime value, deep enough for the SDK's uses. */
function tsType(v, depth = 0) {
  if (v === null) return "null";
  if (typeof v === "function") return "(...args: any[]) => any";
  if (typeof v === "bigint") return "bigint";
  if (typeof v === "number") return "number";
  if (typeof v === "boolean") return "boolean";
  if (typeof v === "string") return "string";
  if (Array.isArray(v)) {
    if (depth > 2 || v.length === 0) return "readonly any[]";
    return `readonly ${tsType(v[0], depth + 1)}[]`;
  }
  if (typeof v === "object") {
    if (depth > 2) return "Record<string, any>";
    const keys = Object.keys(v);
    if (keys.length === 0 || keys.length > 40) return "Record<string, any>";
    return `{ ${keys.map((k) => `readonly ${JSON.stringify(k)}: ${tsType(v[k], depth + 1)}`).join("; ")} }`;
  }
  return "any";
}

/**
 * TYPE-ONLY exports the vendored sources import with `import type`. Reflection cannot see a type,
 * but every one of these is a union OVER A RUNTIME ARRAY the module does export — so the union is
 * DERIVED from that array's actual members rather than typed out here. Adding an entry means
 * naming the array it comes from, which keeps the "one declaration" property intact.
 */
const DERIVED_TYPES = { PlatformSettlementStatus: "PLATFORM_SETTLEMENT_STATUSES" };

const typeLines = Object.entries(DERIVED_TYPES).map(([typeName, arrayName]) => {
  const arr = mod[arrayName];
  if (!Array.isArray(arr) || arr.length === 0) {
    console.error(`[schema-dts] ${typeName} is derived from ${arrayName}, which the schema does not export as a non-empty array`);
    process.exit(1);
  }
  return `  export type ${typeName} = ${arr.map((v) => JSON.stringify(v)).join(" | ")};`;
});

const names = Object.keys(mod).filter((n) => n !== "default").sort();
const lines = names.map((n) => {
  const v = mod[n];
  if (typeof v === "function") return `  export function ${n}(...args: any[]): any;`;
  return `  export const ${n}: ${tsType(v)};`;
});

const body = `// SPDX-License-Identifier: MIT
// GENERATED by scripts/gen-schema-dts.mjs — DO NOT EDIT.
//
// \`@relics/project-schema\` is dependency-free plain ESM with no TypeScript of its own; that is a
// property of the OFFLINE kit and must not change to suit this networked package. Rather than
// hand-maintaining a second description of the schema's surface — which is the same defect class as
// a hand-typed field order — this file is REFLECTED from the module's real exports.
//
// Regenerate with: npm run launch:dts
declare module "@relics/project-schema" {
${typeLines.join("\n")}
${lines.join("\n")}
  const _default: unknown;
  export default _default;
}
`;

if (process.argv.includes("--check")) {
  const { readFileSync } = await import("node:fs");
  if (readFileSync(OUT, "utf8") !== body) { console.error("[schema-dts] DRIFT — run `npm run launch:dts`"); process.exit(1); }
  console.log("[schema-dts] OK");
} else {
  writeFileSync(OUT, body);
  console.log(`[schema-dts] reflected ${names.length} value exports + ${typeLines.length} derived type(s)`);
}
